import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import sharp from 'file:///C:/Users/qtas5/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/sharp/dist/index.mjs';
import { chromium } from 'file:///C:/Users/qtas5/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs';
const output='output/motion/man-in-clouds/qa';
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const raw=buffer=>sharp(buffer).removeAlpha().raw().toBuffer();
const delta=(a,b)=>{assert.equal(a.length,b.length);let sum=0;for(let i=0;i<a.length;i++)sum+=Math.abs(a[i]-b[i]);return sum/a.length;};
const report={checks:[],measurements:{}};
try{
  const page=await browser.newPage({viewport:{width:1536,height:1024},deviceScaleFactor:1});
  await page.goto('http://127.0.0.1:8976/?qa&render');
  await page.waitForFunction(()=>document.documentElement.dataset.ready||document.documentElement.dataset.error);
  assert.equal(await page.evaluate(()=>document.documentElement.dataset.error),undefined);
  const capture=async(time,effects,name)=>{
    await page.evaluate(({time,effects})=>{window.cloudPreview.renderer.effects(...effects);window.cloudPreview.seek(time);},{time,effects});
    return raw(await page.locator('#scene').screenshot(name?{path:`${output}/${name}.png`}:{}));
  };
  const quiet1=await capture(1,[false,false,false]);
  const rain1=await capture(1,[true,false,false],'rain');
  const quiet2=await capture(1.35,[false,false,false]);
  const rain2=await capture(1.35,[true,false,false]);
  const rainDifference=delta(quiet1,rain1);
  let movement=0;for(let i=0;i<quiet1.length;i++)movement+=Math.abs((rain1[i]-quiet1[i])-(rain2[i]-quiet2[i]));
  movement/=quiet1.length;
  assert(rainDifference>0.035,`Rain invisible: ${rainDifference}`);
  assert(movement>0.035,`Rain does not travel: ${movement}`);
  const calm=await capture(3.3,[true,false,false]);
  const wind=await capture(3.3,[true,true,false],'wind');
  const windDifference=delta(calm,wind);assert(windDifference>0.5);
  const paint=await capture(8.3,[true,true,false]);
  const scan=await capture(8.3,[true,true,true],'scanner');
  const scanDifference=delta(paint,scan);assert(scanDifference>0.2,`Scanner invisible: ${scanDifference}`);
  await page.evaluate(()=>window.cloudPreview.renderer.wireframe(true));
  const wire=await page.locator('#scene').screenshot({path:`${output}/vector-contours.png`});
  const stats=await sharp(wire).stats();assert(stats.channels[0].mean>1&&stats.channels[0].mean<45);
  await page.evaluate(()=>window.cloudPreview.renderer.wireframe(false));
  assert.equal(await page.evaluate(()=>window.cloudPreview.renderer.gpu_error()),0);
  report.measurements={rainDifference,rainMovement:movement,windDifference,scanDifference,vectorMean:stats.channels[0].mean};
  report.checks.push('Moving rain is isolated from camera movement','Wind changes cloth/cloud geometry','Scanner reveals the vector layer','Pure contour view contains real line geometry','No GPU errors');
  await page.goto('http://127.0.0.1:8976/');
  await page.waitForFunction(()=>document.documentElement.dataset.ready);
  await page.locator('#edges').click();assert.equal(await page.locator('#edges').getAttribute('aria-pressed'),'true');
  await page.locator('#scan').click();assert.equal(await page.locator('#edges').getAttribute('aria-pressed'),'false');
  await page.waitForTimeout(700);
  assert.equal(await page.evaluate(()=>window.cloudPreview.renderer.gpu_error()),0);
  report.checks.push('Contour toggle and manual scan buttons work');
  await fs.writeFile(`${output}/effects-report.json`,JSON.stringify(report,null,2));
  console.log(JSON.stringify(report,null,2));
}finally{await browser.close();}
