"""Rasterizes the spoken words and the altimeter's glyphs in Disket Mono once:
white on black, one 128 px row per word, and writes src/generated.rs with the
ink of every row. Everything else in the scene is computed in Rust and its
shaders; these letters are the scene's only immutable input.

    python graphics/inner-descent/tools/prepare-assets.py

The same font and setting as the other scenes' labels: 64 px, 6 px letter
spacing, baseline 86 px into each row. The last row holds the altimeter's
glyphs in fixed cells (Disket Mono is monospaced), so the shader can print
any reading from them.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SCENE = Path(__file__).resolve().parent.parent
FONT = SCENE.parent / "product-engine/engine/assets/fonts/Disket-Mono-Regular.ttf"
# The phrases he says aloud (lib.rs `SAID`), then the thought in his helmet.
WORDS = [
    "Я ЗДЕСЬ",
    "Я СЛЫШУ",
    "Я ОЩУЩАЮ",
    "Я ЗАМЕЧАЮ",
    "Я ОСОЗНАЮ",
    "Я ЕСТЬ",
    "ТЕПЛО",
]
# The altimeter's glyphs, one fixed cell each (lib.rs `glyph`).
GLYPHS = "0123456789КМ"
ATLAS = 1024
ROW = 128
BASELINE = 86
ROWS = len(WORDS) + 1

font = ImageFont.truetype(str(FONT), 64)
atlas = Image.new("L", (ATLAS, ROW * ROWS), 0)
draw = ImageDraw.Draw(atlas)
for i, line in enumerate(WORDS):
    x = 24.0
    for ch in line:
        draw.text((x, ROW * i + BASELINE), ch, font=font, fill=255, anchor="ls")
        x += font.getlength(ch) + 6
advances = {font.getlength(ch) for ch in GLYPHS}
if len(advances) != 1:
    raise SystemExit(f"the glyphs are not monospaced: {sorted(advances)}")
adv = advances.pop() + 6
for k, ch in enumerate(GLYPHS):
    draw.text((24.0 + k * adv, ROW * len(WORDS) + BASELINE), ch, font=font, fill=255, anchor="ls")
if 24.0 + len(GLYPHS) * adv > ATLAS - 8:
    raise SystemExit("the glyph row does not fit the atlas")
px = atlas.load()
ink, top, bottom = [], ROW, 0
for i in range(ROWS):
    x0, x1 = ATLAS, -1
    for y in range(ROW):
        for x in range(ATLAS):
            if px[x, ROW * i + y] > 24:
                x0, x1 = min(x0, x), max(x1, x)
                top, bottom = min(top, y), max(bottom, y)
    if x1 < 0:
        raise SystemExit(f"row {i} has no ink")
    if x1 + 1 > ATLAS - 8:
        raise SystemExit(f"row {i} does not fit the atlas")
    ink.append((x0, x1 + 1))
# A capital's height: the ink of «Н» above the baseline.
cap = -font.getbbox("Н", anchor="ls")[1]
atlas.convert("RGB").save(SCENE / "assets/labels.png", optimize=True)
rows = "\n".join(f"    [{a:.1f}, {b:.1f}]," for a, b in ink[: len(WORDS)])
(SCENE / "src/generated.rs").write_text(f"""//! Generated by tools/prepare-assets.py from the spoken words and the altimeter's glyphs.

/// The labels' atlas: its width and height (px), rows of 128 px.
pub const ATLAS: [f32; 2] = [{ATLAS}.0, {ROW * ROWS}.0];
/// Ink of every word row (x0, x1, px), in the order of `tools/prepare-assets.py`.
pub const LABEL_INK: [[f32; 2]; {len(WORDS)}] = [
{rows}
];
/// The rows' common ink band (top, bottom, px inside a row), the baseline
/// inside a row, and a capital's height (px).
pub const LABEL_BAND: [f32; 2] = [{top:.1f}, {bottom + 1:.1f}];
pub const LABEL_BASE: f32 = {BASELINE:.1f};
pub const LABEL_CAP: f32 = {cap:.1f};
/// The altimeter's glyph row: its index, the first cell's left edge and the
/// cell advance (px). Cell k holds `GLYPHS[k]`.
pub const GLYPH_ROW: f32 = {len(WORDS)}.0;
pub const GLYPH_X0: f32 = 24.0;
pub const GLYPH_ADV: f32 = {adv:.1f};
pub const GLYPHS: &str = "{GLYPHS}";
""", encoding="utf-8", newline="\n")
print(f"Prepared labels.png ({ATLAS} x {ROW * ROWS}) and src/generated.rs.")
