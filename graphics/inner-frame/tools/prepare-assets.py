"""Rasterizes the drawing's callouts in Disket Mono once: white on black,
one 128 px row per word, and writes src/generated.rs with the ink of every
row. Everything else in the scene is computed in Rust and its shaders; these
words are the scene's only immutable input.

    python graphics/inner-frame/tools/prepare-assets.py

The same font and setting as the other scenes' labels: 64 px, 6 px letter
spacing, baseline 86 px into each row.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SCENE = Path(__file__).resolve().parent.parent
FONT = SCENE.parent / "product-engine/engine/assets/fonts/Disket-Mono-Regular.ttf"
# One callout for each of the six signals, then the anchor and the frame
# (lib.rs `Word`), in the page's own words.
WORDS = [
    "ЗВУКИ",
    "ДВИЖЕНИЕ",
    "СВЕТ И ТЕНИ",
    "ТЕМПЕРАТУРА",
    "ВИБРАЦИИ ПОЛА",
    "ОБЪЕМ ПРОСТРАНСТВА",
    "ЯКОРЬ",
    "КАРКАС",
]
ATLAS = 1536
ROW = 128
BASELINE = 86

font = ImageFont.truetype(str(FONT), 64)
atlas = Image.new("L", (ATLAS, ROW * len(WORDS)), 0)
draw = ImageDraw.Draw(atlas)
for i, line in enumerate(WORDS):
    x = 24.0
    for ch in line:
        draw.text((x, ROW * i + BASELINE), ch, font=font, fill=255, anchor="ls")
        x += font.getlength(ch) + 6
px = atlas.load()
ink, top, bottom = [], ROW, 0
for i in range(len(WORDS)):
    x0, x1 = ATLAS, -1
    for y in range(ROW):
        for x in range(ATLAS):
            if px[x, ROW * i + y] > 24:
                x0, x1 = min(x0, x), max(x1, x)
                top, bottom = min(top, y), max(bottom, y)
    if x1 + 1 > ATLAS - 8:
        raise SystemExit(f"row {i} does not fit the atlas")
    ink.append((x0, x1 + 1))
# A capital's height: the ink of «Н» above the baseline.
cap = -font.getbbox("Н", anchor="ls")[1]
atlas.convert("RGB").save(SCENE / "assets/labels.png", optimize=True)
rows = "\n".join(f"    [{a:.1f}, {b:.1f}]," for a, b in ink)
(SCENE / "src/generated.rs").write_text(f"""//! Generated by tools/prepare-assets.py from the drawing's callouts.

/// The labels' atlas: its width and height (px), rows of 128 px.
pub const ATLAS: [f32; 2] = [{ATLAS}.0, {ROW * len(WORDS)}.0];
/// Ink of every row (x0, x1, px), in the order of `tools/prepare-assets.py`.
pub const LABEL_INK: [[f32; 2]; {len(WORDS)}] = [
{rows}
];
/// The rows' common ink band (top, bottom, px inside a row), the baseline
/// inside a row, and a capital's height (px).
pub const LABEL_BAND: [f32; 2] = [{top:.1f}, {bottom + 1:.1f}];
pub const LABEL_BASE: f32 = {BASELINE:.1f};
pub const LABEL_CAP: f32 = {cap:.1f};
""", encoding="utf-8", newline="\n")
print(f"Prepared labels.png ({ATLAS} x {ROW * len(WORDS)}) and src/generated.rs.")
