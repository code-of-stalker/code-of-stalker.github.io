"""Rasterizes the words of the page in Disket Mono once: white on black, one
128 px row per phrase, and writes src/generated.rs with the ink of every row.
The eye, the eyelid, the lashes and the reflection are computed in Rust and
its shaders; these words are the scene's only immutable input.

    python graphics/true-sight/tools/prepare-assets.py

Pillow stands in for the browser canvas the older scenes used: the same font,
64 px, 6 px letter spacing, baseline 86 px into each row.
"""
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

SCENE = Path(__file__).resolve().parent.parent
FONT = SCENE.parent / "product-engine/engine/assets/fonts/Disket-Mono-Regular.ttf"
# The page's words, in the order of the film. A quiet line stays written while
# bright lines take turns under it: «И пока ты» over the three «не»,
# «Но как только возникло» over Видение, Распознавание and Различение.
WORDS = [
    "И ПОКА ТЫ", "НЕ ОЩУТИЛ СТУПНИ,", "НЕ УСЛЫШАЛ ГОЛОС,",
    "НЕ ОТСЛЕДИЛ, КАК МЫСЛЬ ДЕЛАЕТ ВЫВОД,", "ТЫ НЕ ПРОСНУЛСЯ.",
    "НО КАК ТОЛЬКО ВОЗНИКЛО", "ИСТИННОЕ ВИДЕНИЕ,", "ИСТИННОЕ РАСПОЗНАВАНИЕ",
    "И РАЗЛИЧЕНИЕ —", "ВОЗНИКАЕТ", "ТЫ АБСОЛЮТНЫЙ, ТЫ НАСТОЯЩИЙ.",
]
# Wider than the older scenes' 1536: the longest «не» line is one row.
ATLAS = 2048
ROW = 128

font = ImageFont.truetype(str(FONT), 64)
atlas = Image.new("L", (ATLAS, ROW * len(WORDS)), 0)
draw = ImageDraw.Draw(atlas)
for i, line in enumerate(WORDS):
    x = 24.0
    for ch in line:
        draw.text((x, ROW * i + 86), ch, font=font, fill=255, anchor="ls")
        x += font.getlength(ch) + 6
px = atlas.load()
ink, top, bottom = [], ROW, 0
for i in range(len(WORDS)):
    x0, x1 = ATLAS, -1
    for y in range(ROW):
        for x in range(ATLAS):
            if px[x, ROW * i + y] > 24:
                x0, x1 = min(x0, x), max(x1, x)
                top, bottom = min(top, y), max(bottom, y)
    if x1 + 1 > ATLAS - 8:
        raise SystemExit(f"row {i} does not fit the atlas")
    ink.append((x0, x1 + 1))
atlas.convert("RGB").save(SCENE / "assets/labels.png", optimize=True)
rows = "\n".join(f"    [{a:.1f}, {b:.1f}]," for a, b in ink)
(SCENE / "src/generated.rs").write_text(f"""//! Generated by tools/prepare-assets.py from the words of the page.

/// The labels' atlas: its width and height (px), rows of 128 px.
pub const ATLAS: [f32; 2] = [{ATLAS}.0, {ROW * len(WORDS)}.0];
/// Ink of every row (x0, x1, px), in the order of `tools/prepare-assets.py`.
pub const LABEL_INK: [[f32; 2]; {len(WORDS)}] = [
{rows}
];
/// The rows' common ink band (top, bottom, px inside a row), accents and
/// commas included. Capitals stand 44 px tall in it.
pub const LABEL_BAND: [f32; 2] = [{top:.1f}, {bottom + 1:.1f}];
""", encoding="utf-8", newline="\n")
print(f"Prepared labels.png ({ATLAS} x {ROW * len(WORDS)}) and src/generated.rs.")
