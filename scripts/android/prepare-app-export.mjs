// Turn a plain `expo export --platform web` into the web content of the Android app.
//
// The shell (android-app/) serves this folder from the APK at
// https://appassets.androidplatform.net/, so every file is already on the device.
// Compared with the site (scripts/prepare-web-cache.mjs) the page keeps the same
// Content-Security-Policy, frame guard and manifest tags, but gets no release
// service worker, update probe or self-heal: a new version is a new APK.
import { createHash } from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { prepareAppManifest } from '../web-cache/app-manifest.mjs';
import { secureShell } from '../web-cache/shell-security.mjs';

// Files only the site's release cache uses; an app export must never carry them.
const siteOnly = ['graphics-cache-updates.js', 'graphics-cache-worker.js', 'graphics-cache-manifest.json', 'graphics-cache-version.json', '404.html'];

// The app's own small worker. WebView never keeps V8's compiled code for files the app
// serves itself (WebViewAssetLoader), so the 2.9 MB entry script was compiled from scratch
// on every start (~0.3 s on Art's phone) while the site reuses it from its worker's cache.
// This worker only copies the page's hashed scripts from the APK into Cache Storage, where
// Chrome keeps their compiled code. No updates, no other files: a new APK lists new names.
// It fills the cache after the install event on purpose: a script stored during install gets
// an eager code cache that still ran entry in ~0.45 s on Art's phone, while a script stored
// later gets the code its first run compiled, and entry then runs in ~0.12 s, as on the site.
export const scriptCacheWorker = 'app-script-cache.js';
export const scriptCacheRegister = 'app-script-cache-register.js';

// `release` names the cache: it must change whenever any listed file's bytes change.
export function scriptCacheSource(scripts, release) {
  return `// Code Of Stalker app: page scripts in Cache Storage, so V8 reuses their compiled code.
// Generated by scripts/android/prepare-app-export.mjs; every file is already in the APK.
const CACHE = 'app-scripts-${release}';
const SCRIPTS = ${JSON.stringify(scripts)};
const LISTED = new Set(SCRIPTS);
// Never called during install (see prepare-app-export.mjs); adds only what is missing, so the
// compiled code Chrome keeps next to each stored script survives.
const fill = () => caches.open(CACHE).then(async cache => {
  const stored = new Set((await cache.keys()).map(request => new URL(request.url).pathname));
  const missing = SCRIPTS.filter(pathname => !stored.has(pathname));
  if (missing.length) await cache.addAll(missing);
});
self.addEventListener('install', event => {
  // Navigations and every other file go straight to the APK without waking this worker.
  if (event.addRoutes && typeof URLPattern === 'function') {
    try {
      const added = event.addRoutes([
        ...SCRIPTS.map(pathname => ({ condition: { urlPattern: new URLPattern({ pathname }) }, source: { cacheName: CACHE } })),
        { condition: { urlPattern: new URLPattern({}) }, source: 'network' },
      ]);
      if (added) event.waitUntil(added.catch(() => {}));
    } catch {}
  }
  self.skipWaiting();
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(key => key.startsWith('app-scripts-') && key !== CACHE).map(key => caches.delete(key))))
    .then(fill)
    .catch(() => {})
    .then(() => self.clients.claim()));
});
// The page asks once per start, after load: refill what an interrupted activation missed.
self.addEventListener('message', event => {
  if (event.data === 'fill') event.waitUntil(fill().catch(() => {}));
});
self.addEventListener('fetch', event => {
  const url = new URL(event.request.url);
  if (event.request.method !== 'GET' || url.origin !== self.location.origin || !LISTED.has(url.pathname)) return;
  event.respondWith(caches.match(event.request, { cacheName: CACHE }).then(hit => hit || fetch(event.request)));
});
`;
}

const registerSource = `// Code Of Stalker app: start the script cache once the page is up, never before the first paint.
(() => {
  if (!('serviceWorker' in navigator)) return;
  const start = () => setTimeout(() => navigator.serviceWorker.register('/${scriptCacheWorker}', { scope: '/' })
    .then(() => navigator.serviceWorker.ready)
    .then(registration => registration.active?.postMessage('fill'))
    .catch(() => {}), 2000);
  if (document.readyState === 'complete') start(); else addEventListener('load', start, { once: true });
})();
`;

// `scriptCache: false` leaves the worker out: the iOS shell serves a custom scheme, and
// WKWebView runs no service worker there (scripts/ios/prepare-ios-export.mjs).
export async function prepareAppExport(outputDirectory, { scriptCache = true } = {}) {
  const root = await fs.realpath(path.resolve(outputDirectory));
  const htmlPath = path.join(root, 'index.html');
  let html = await fs.readFile(htmlPath, 'utf8');
  if (!html.includes('</body>')) throw new Error('Export has no HTML body');
  html = html.replace(/<script id="watcher-graphics-cache"[^>]*><\/script>/g, '');
  html = await secureShell(await prepareAppManifest(root, html));
  if (/serviceWorker|graphics-cache-updates/.test(html)) throw new Error('App shell must not register the site release worker');
  const scriptDir = path.join(root, '_expo', 'static', 'js', 'web');
  const names = (await fs.readdir(scriptDir)).filter(name => name.endsWith('.js')).sort();
  if (!names.length) throw new Error('Export has no page scripts');
  if (scriptCache) {
    const digest = createHash('sha256');
    for (const name of names) digest.update(name).update('\0').update(await fs.readFile(path.join(scriptDir, name))).update('\0');
    const scripts = names.map(name => `/_expo/static/js/web/${name}`);
    await fs.writeFile(path.join(root, scriptCacheWorker), scriptCacheSource(scripts, digest.digest('hex').slice(0, 16)));
    await fs.writeFile(path.join(root, scriptCacheRegister), registerSource);
    html = html.replace('</body>', `<script src="/${scriptCacheRegister}" defer></script></body>`);
  } else {
    await fs.rm(path.join(root, scriptCacheWorker), { force: true });
    await fs.rm(path.join(root, scriptCacheRegister), { force: true });
  }
  await fs.writeFile(htmlPath, html);
  for (const name of siteOnly) await fs.rm(path.join(root, name), { force: true });
  await fs.rm(path.join(root, 'graphics-cache-assets'), { recursive: true, force: true });
  let files = 0, bytes = 0;
  async function visit(directory) {
    for (const entry of await fs.readdir(directory, { withFileTypes: true })) {
      const full = path.join(directory, entry.name);
      if (entry.isSymbolicLink()) throw new Error(`Export must not contain symbolic links: ${full}`);
      if (entry.isDirectory()) await visit(full);
      else if (entry.isFile()) { files++; bytes += (await fs.stat(full)).size; }
    }
  }
  await visit(root);
  return { files, bytes };
}

if (process.argv[1] && import.meta.url === pathToFileURL(path.resolve(process.argv[1])).href) {
  console.log(JSON.stringify(await prepareAppExport(process.argv[2] ?? '.expo-android-export')));
}
