// Serialize at build time: native Hermes does not need Function.toString().
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const dir = path.join(__dirname, '../src/features/product/diary');
const source = ts.createSourceFile('editor.ts', fs.readFileSync(path.join(dir, 'text-editor-document.ts'), 'utf8'), ts.ScriptTarget.Latest, true);
const runtime = source.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === 'textEditorRuntime');
if (!runtime) throw new Error('Diary editor runtime not found');
// Config travels in a JSON element, so this inline script is identical for
// every entry and the web shell's Content-Security-Policy can allow its hash.
const code = ts.transpileModule(runtime.getText(source).replace(/^export /, ''), { compilerOptions: { target: ts.ScriptTarget.ES2022 } }).outputText
  + "textEditorRuntime(JSON.parse(document.getElementById('diary-editor-config').textContent));\n";
fs.writeFileSync(path.join(dir, 'text-editor-runtime.generated.ts'), '// Generated by scripts/generate-diary-editor.cjs; edit text-editor-document.ts.\nexport const diaryTextEditorScript = ' + JSON.stringify(code) + ';\n');
