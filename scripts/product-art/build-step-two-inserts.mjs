const crowd = fs.readFileSync(path.join(root, 'scripts/product-art/src/laboratory/assets/crowd-awareness.svg'), 'utf8');
function crowdGroup(id) {
  const start = crowd.indexOf(`<g id="${id}"`);
  if (start < 0) throw new Error(`Missing approved crowd figure ${id}`);
  const tags = /<g\b[^>]*>|<\/g>/g; tags.lastIndex = start;
  let depth = 0, tag;
  while ((tag = tags.exec(crowd))) {
    depth += tag[0].startsWith('</') ? -1 : 1;
    if (depth === 0) return crowd.slice(start, tags.lastIndex).replaceAll('mcw-id-', 'inward-');
  }
  throw new Error(`Incomplete crowd figure ${id}`);
}
const inwardPeople = ['05-woman-bob', '02-man-crop', '10-woman-pixie', '07-man-parted']
  .flatMap(id => ['shape', 'drawing'].map(part => crowdGroup(`mcw-id-${part}-${id}`))).join('\n');
